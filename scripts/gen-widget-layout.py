#!/usr/bin/env python3
"""Writes android/app/src/main/res/layout/fast_widget.xml: three pictures (one per tab) under invisible touch zones of the same proportions.
Run it again when a page gains or loses a cell: the zones are named z_<page>_<row>_<column>, the tabs t_<name>."""
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "android/app/src/main/res/layout/fast_widget.xml"
# page letter, weights of the cells of the first row, of the second row (None: the page is one row)
PAGES = [
    ("a", [1, 3, 1, 1], [1, 1, 1, 1, 1]), # Agent: Chambre en cours (when there is one) | Super agent | Claude | Question ; Écoute | Ajouter | Scénario | Cast TV | Schéma
    ("f", [6, 1, 1], [1, 1, 1, 1, 1]), # Files: the repository | see it | change its session ; docs | images | vidéos | apps | pages
    ("v", [1, 1], [1, 1, 1]),          # Game: Wallet | Zone ; Lien | QR code | Favoris
]
TABS = [("t_settings", 55), ("t_agent", 100), ("t_files", 100), ("t_voir", 100), ("t_upd", 55)]


def build():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<!-- The widget: five pictures drawn by WidgetArt (one per tab) turned by a ViewFlipper, under invisible touch zones (a second ViewFlipper) of the same proportions: the strip of the tabs is the top 7/22, the page the rest. Generated by scripts/gen-widget-layout.py. -->',
         '<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android" android:id="@+id/fw_root" android:layout_width="match_parent" android:layout_height="match_parent">',
         '<ViewFlipper android:id="@+id/fw_img_flip" android:layout_width="match_parent" android:layout_height="match_parent" android:inAnimation="@null" android:outAnimation="@null">']
    o += [f'<ImageView android:id="@+id/fw_img{i}" android:layout_width="match_parent" android:layout_height="match_parent" android:scaleType="fitXY"/>' for i in range(len(PAGES))]
    o += ['</ViewFlipper>',
          '<LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" android:orientation="vertical">',
          '<LinearLayout android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="7" android:orientation="horizontal">',
          '<FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="7"/>',
          '<LinearLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="86" android:orientation="horizontal">']
    o += [f'<FrameLayout android:id="@+id/{tid}" android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="{w}"/>' for tid, w in TABS]
    o += ['</LinearLayout>',
          '<FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="7"/>',
          '</LinearLayout>',
          '<ViewFlipper android:id="@+id/fw_zone_flip" android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="15" android:inAnimation="@null" android:outAnimation="@null">']
    for letter, r0, r1 in PAGES:
        o.append('<LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" android:orientation="vertical">')
        o.append(f'<LinearLayout android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="{10 if r1 else 15}" android:orientation="horizontal">')
        o += [f'<FrameLayout android:id="@+id/z_{letter}_0_{c}" android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="{w}"/>' for c, w in enumerate(r0)]
        o.append('</LinearLayout>')
        if r1:
            o += ['<LinearLayout android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="5" android:orientation="horizontal">',
                  '<FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="7"/>',
                  '<LinearLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="86" android:orientation="horizontal">']
            o += [f'<FrameLayout android:id="@+id/z_{letter}_1_{c}" android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="{w}"/>' for c, w in enumerate(r1)]
            o += ['</LinearLayout>', '<FrameLayout android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="7"/>', '</LinearLayout>']
        o.append('</LinearLayout>')
    o.append('</ViewFlipper></LinearLayout></FrameLayout>')
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    OUT.write_text(build())
    print("written", OUT)
